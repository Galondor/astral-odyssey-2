export const getSellPrice = (item) =>
  Number.isFinite(item?.price) && item.price >= 0
    ? Math.floor(item.price / 2)
    : null;

const GEMSTONE_RARITY_COSTS = Object.fromEntries(
  RARITIES.map((rarity, index) => [rarity.name, (index + 1) * 100]),
);

export const getGemstoneRemovalCost = (gemstone) =>
  GEMSTONE_RARITY_COSTS[gemstone?.rarity] || null;

const getGemstoneTarget = (player, target) => {
  if (target?.kind === "inventory") {
    const inventory = [...(player.inventory || [])];
    const item = inventory[target.index];
    return item && !item.twoHandedOf
      ? { item, inventory, location: "inventory" }
      : null;
  }
  if (target?.kind === "equipment") {
    const equipment = { ...(player.equipment || {}) };
    const item = equipment[target.slotKey];
    return item && !item.twoHandedOf
      ? { item, equipment, location: "equipment" }
      : null;
  }
  return null;
};

export function socketGemstone(gemstoneId, target) {
  const player = getPlayer();
  if (!player || getEnemy()) return { ok: false, reason: "combat" };
  const gemstones = [...(player.gemstones || [])];
  const gemstoneIndex = gemstones.findIndex(
    (gemstone) => gemstone.id === gemstoneId,
  );
  const gemstone = gemstones[gemstoneIndex];
  const targetItem = getGemstoneTarget(player, target);
  if (!gemstone || !targetItem) return { ok: false, reason: "invalid" };
  if (targetItem.item.gemstone) return { ok: false, reason: "occupied" };

  gemstones.splice(gemstoneIndex, 1);
  const item = { ...targetItem.item, gemstone };
  const changes = { gemstones };
  if (targetItem.location === "inventory") {
    targetItem.inventory[target.index] = item;
    changes.inventory = targetItem.inventory;
  } else {
    targetItem.equipment[target.slotKey] = item;
    changes.equipment = targetItem.equipment;
  }
  setPlayer(recalculateStats(player, changes));
  return { ok: true };
}

export function removeGemstone(target) {
  const player = getPlayer();
  if (!player || getEnemy()) return { ok: false, reason: "combat" };
  const targetItem = getGemstoneTarget(player, target);
  if (!targetItem?.item.gemstone) return { ok: false, reason: "invalid" };
  const gemstone = targetItem.item.gemstone;
  const cost = getGemstoneRemovalCost(gemstone);
  if (cost === null) return { ok: false, reason: "invalid" };
  if ((player.astra || 0) < cost) return { ok: false, reason: "astra", cost };

  const item = { ...targetItem.item };
  delete item.gemstone;
  const changes = {
    astra: (player.astra || 0) - cost,
    gemstones: [...(player.gemstones || []), gemstone],
  };
  if (targetItem.location === "inventory") {
    targetItem.inventory[target.index] = item;
    changes.inventory = targetItem.inventory;
  } else {
    targetItem.equipment[target.slotKey] = item;
    changes.equipment = targetItem.equipment;
  }
  setPlayer(recalculateStats(player, changes));
  return { ok: true, cost };
}

const BUYBACK_LIMIT = 10;
const GEAR_TRADER_STOCK_SIZE = 20;
const GEAR_TRADER_QUALITY = [
  { rep: 0, minTier: 0 },
  { rep: 20, minTier: 0, weights: [35, 30, 20, 14, 1] },
  { rep: 80, minTier: 1, weights: [15, 30, 30, 22, 3] },
  { rep: 250, minTier: 2, weights: [0, 15, 35, 45, 5] },
  { rep: 700, minTier: 3, weights: [0, 0, 32, 60, 8] },
  { rep: 1800, minTier: 4, weights: [0, 0, 25, 65, 10] },
];
export const GEAR_TRADER_REFRESH_MS = 30 * 60 * 1000;
const getGearTraderHour = () => Math.floor(Date.now() / GEAR_TRADER_REFRESH_MS);

export const getGearTraderStock = (player = getPlayer()) => {
  const hour = getGearTraderHour();
  if (
    player?.gearTraderStock?.hour === hour &&
    Array.isArray(player.gearTraderStock.items)
  )
    return player.gearTraderStock.items;

  const slots = Object.keys(SLOT_CONFIG);
  const quality =
    [...GEAR_TRADER_QUALITY]
      .reverse()
      .find((entry) => (player?.rep || 0) >= entry.rep) ||
    GEAR_TRADER_QUALITY[0];
  const items = Array.from({ length: GEAR_TRADER_STOCK_SIZE }, () =>
    generateItem(pick(slots), 0, quality, player),
  );
  if (player) setPlayer({ gearTraderStock: { hour, items } });
  return items;
};

export function sellInventoryItem(index) {
  const player = getPlayer();
  if (!player || getEnemy()) return { ok: false };
  const inventory = [...(player.inventory || [])];
  const item = inventory[index];
  const value = getSellPrice(item);
  if (!item || value === null) return { ok: false };
  if (isFavorite(player, "gear", item))
    return { ok: false, reason: "favorite" };
  inventory.splice(index, 1);
  const buyback = [
    { item, price: value },
    ...(player.gearTraderBuyback || []),
  ].slice(0, BUYBACK_LIMIT);
  setPlayer({
    inventory,
    astra: (player.astra || 0) + value,
    gearTraderBuyback: buyback,
  });
  return { ok: true, item, value };
}

export function sellEquippedItem(slotKey) {
  const player = getPlayer();
  if (!player || getEnemy()) return { ok: false };
  const equipment = { ...(player.equipment || {}) };
  const item = equipment[slotKey];
  const value = getSellPrice(item);
  if (!item || item.twoHandedOf || value === null) return { ok: false };
  if (isFavorite(player, "gear", item))
    return { ok: false, reason: "favorite" };

  delete equipment[slotKey];
  if (item.twoHanded) delete equipment.offHand;
  const buyback = [
    { item, price: value },
    ...(player.gearTraderBuyback || []),
  ].slice(0, BUYBACK_LIMIT);
  setPlayer({
    ...recalculateStats(player, {
      equipment,
      astra: (player.astra || 0) + value,
      gearTraderBuyback: buyback,
    }),
  });
  return { ok: true, item, value };
}

export function buyBackGear(index) {
  const player = getPlayer();
  if (!player || getEnemy()) return { ok: false };
  const buyback = [...(player.gearTraderBuyback || [])];
  const entry = buyback[index];
  if (!entry?.item || !Number.isFinite(entry.price) || entry.price < 0)
    return { ok: false };
  if ((player.astra || 0) < entry.price)
    return { ok: false, reason: "astra", price: entry.price };

  buyback.splice(index, 1);
  setPlayer({
    astra: (player.astra || 0) - entry.price,
    inventory: [...(player.inventory || []), entry.item],
    gearTraderBuyback: buyback,
  });
  return { ok: true, item: entry.item, price: entry.price };
}

export function buyGearTraderItem(index) {
  let player = getPlayer();
  if (!player || getEnemy()) return { ok: false };
  const items = [...getGearTraderStock(player)];
  player = getPlayer();
  const item = items[index];
  if (!item || !Number.isFinite(item.price) || item.price < 0)
    return { ok: false };
  if ((player.astra || 0) < item.price)
    return { ok: false, reason: "astra", price: item.price };

  items.splice(index, 1);
  setPlayer({
    astra: (player.astra || 0) - item.price,
    inventory: [...(player.inventory || []), item],
    gearTraderStock: { ...player.gearTraderStock, items },
  });
  return { ok: true, item, price: item.price };
}

// A two-handed weapon in the main hand also fills the off hand with this stat-free placeholder.
const twoHandedPlaceholder = (item) => ({
  twoHandedOf: "mainHand",
  name: item.name,
  rarity: item.rarity,
});

// Moves whatever occupies `key` (resolving a two-handed placeholder to its weapon) back to the inventory.
const vacateSlot = (equipment, inventory, key) => {
  const slotItem = equipment[key];
  if (!slotItem) return;
  const mainKey = slotItem.twoHandedOf || key;
  const item = equipment[mainKey];
  delete equipment[mainKey];
  if (item?.twoHanded) delete equipment.offHand;
  if (item) inventory.push(item);
};

// Equips inventory item at `index`. Ring items use the first empty ring slot, otherwise replace Ring 1.
// Two-handed weapons use both the main hand and off hand; equipping an off hand frees a two-hander.
export function equipItem(index) {
  const p = getPlayer();
  const inventory = [...(p.inventory || [])];
  const item = inventory[index];
  if (!item) return { ok: false };
  if (getEnemy()) return { ok: false, reason: "combat" };
  if (!canEquip(item, p.level)) return { ok: false, reason: "level" };
  const candidates = SLOTS.filter((s) => s.type === item.slot);
  if (!candidates.length) return { ok: false };
  const equipment = { ...(p.equipment || {}) };
  inventory.splice(index, 1);
  if (item.twoHanded) {
    vacateSlot(equipment, inventory, "mainHand");
    vacateSlot(equipment, inventory, "offHand");
    equipment.mainHand = item;
    equipment.offHand = twoHandedPlaceholder(item);
  } else {
    const target = candidates.find((s) => !equipment[s.key]) || candidates[0];
    vacateSlot(equipment, inventory, target.key);
    equipment[target.key] = item;
  }
  setPlayer(recalculateStats(p, { inventory, equipment }));
  return { ok: true };
}

export function unequipItem(slotKey) {
  const p = getPlayer();
  const equipment = { ...(p.equipment || {}) };
  const inventory = [...(p.inventory || [])];
  if (!equipment[slotKey]) return { ok: false };
  if (getEnemy()) return { ok: false, reason: "combat" };
  vacateSlot(equipment, inventory, slotKey);
  setPlayer(recalculateStats(p, { inventory, equipment }));
  return { ok: true };
}
