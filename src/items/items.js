const formatValue = (stat, v) => {
  const n = PERCENT_STATS.includes(stat)
    ? `${round(Math.abs(v) * 100, 1)}%`
    : Math.abs(v);
  return `${v < 0 ? "-" : "+"}${n}`;
};

export const itemTooltip = (item, extra) => {
  if (!item) return null;
  const slot = SLOTS.find((s) => s.type === item.slot);
  const stats = [];
  if (item.mainStat) {
    stats.push({
      label: STAT_LABELS[item.mainStat.stat] || item.mainStat.stat,
      value: formatValue(item.mainStat.stat, item.mainStat.value),
      color: "#ffd479",
      tier: item.mainStat.tier !== undefined ? `T${item.mainStat.tier}` : undefined,
      tierColor: TIER_COLORS[item.mainStat.tier],
    });
  }
  for (const [k, v] of Object.entries(item.subStats || {})) {
    stats.push({
      label: STAT_LABELS[k] || k,
      value: formatValue(k, v),
      color: v < 0 ? "#ff6b6b" : "#7bd88f",
      tier: item.subTiers?.[k] !== undefined ? `T${item.subTiers[k]}` : undefined,
      tierColor: TIER_COLORS[item.subTiers?.[k]],
    });
  }
  const slotLabel = slot ? slot.label.replace(/ \d$/, "") : item.slot;
  const level = getPlayer()?.level || 1;
  const tags = [
    slotLabel,
    item.twoHanded && "Two-handed",
    `Gear score ${getItemGearScore(item)}`,
  ].filter(Boolean);
  const abilityText = item.ability
    ? `${item.ability.name}: ${findAbility(item.ability)?.description || item.ability.description}`
    : "";
  return {
    title: item.name,
    titleColor: RARITY_COLORS[item.rarity],
    subtitle: `${item.rarity}, Item Level ${item.iLevel} • Equip level ${getEquipLevel(item)}`,
    description: [abilityText].filter(Boolean),
    stats,
    footer: [
      extra,
      !canEquip(item, level) && `Requires level ${getEquipLevel(item)} • `,
      `Value: ${item.price}`,
    ].filter(Boolean),
    tags,
  };
};

// Equipped items an item would replace, and those worth showing beside it (all rings for a ring).
const getComparedItems = (item) => {
  const equipment = getEquipment();
  const candidates = SLOTS.filter((s) => s.type === item.slot);
  const real = (key) => {
    const e = equipment[key];
    return e?.twoHandedOf ? equipment[e.twoHandedOf] : e;
  };
  const unique = (list) => [...new Set(list.filter(Boolean))];
  const shown = unique(candidates.map((s) => real(s.key)));
  let replaced;
  if (item.twoHanded) {
    replaced = unique([real("mainHand"), real("offHand")]);
  } else {
    const target = candidates.find((s) => !equipment[s.key]) || candidates[0];
    replaced =
      target && equipment[target.key] ? unique([real(target.key)]) : [];
  }
  return {
    shown: item.twoHanded ? unique([...shown, ...replaced]) : shown,
    replaced,
  };
};

const sumStats = (items) => {
  const out = {};
  for (const it of items) {
    if (it.mainStat)
      out[it.mainStat.stat] = (out[it.mainStat.stat] || 0) + it.mainStat.value;
    for (const [k, v] of Object.entries(it.subStats || {}))
      out[k] = (out[k] || 0) + v;
  }
  return out;
};

// Item tooltip plus the change versus what it would replace, and the equipped gear in the same slot(s).
export const itemComparisonTooltip = (item, extra) => {
  const base = itemTooltip(item, extra);
  if (!base) return base;
  const { shown, replaced } = getComparedItems(item);
  const next = sumStats([item]);
  const prev = sumStats(replaced);
  const changes = Object.keys({ ...next, ...prev })
    .map((k) => [k, round((next[k] || 0) - (prev[k] || 0))])
    .filter(([, d]) => d !== 0)
    .map(([k, d]) => ({
      label: STAT_LABELS[k] || k,
      value: formatValue(k, d),
      color: d < 0 ? "#ff6b6b" : "#7bd88f",
    }));
  const sections = [];
  if (!shown.length) {
    sections.push({
      title: "Nothing equipped",
      subtitle: "This slot is empty",
    });
  } else {
    sections.push({
      title: "If equipped",
      subtitle: replaced.length
        ? "Change versus replaced gear"
        : "A free slot is used",
      stats: changes,
    });
    for (const e of shown) {
      const t = itemTooltip(e);
      sections.push({
        ...t,
        subtitle: `Equipped • ${t.subtitle}`,
        footer: replaced.includes(e) ? "Would be replaced" : undefined,
      });
    }
  }
  return { ...base, sections };
};

// Equip level is iLevel - 1, plus bonuses for abilities and Legendary rarity.
// Always derived, so items saved under an older formula stay consistent.
export const getEquipLevel = (item) => {
  const level = (item?.iLevel || 1) - 1;
  return Math.min(
    100,
    Math.max(1, level + (item?.ability ? 1 : 0) + (item?.rarity === "Legendary" ? 1 : 0)),
  );
};

export const canEquip = (item, level = getPlayer()?.level || 1) =>
  level >= getEquipLevel(item);

