const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
const randInt = (max) => Math.floor(Math.random() * Math.max(1, max)) + 1;
const round = (n, d = 3) => Math.round(n * 10 ** d) / 10 ** d;

const rollRarity = () => {
  let roll = Math.random();
  for (const r of RARITIES) {
    if (roll < r.chance) return r;
    roll -= r.chance;
  }
  return RARITIES[0];
};

const rollSubStatValue = (key, iLevel) => {
  const cap = SUBSTAT_CAPS[key] * iLevel;
  if (key === "criticalDamage")
    return round(Math.max(0.01, Math.ceil(Math.random() * cap * 100) / 100), 2);
  return randInt(cap);
};

const scaleValue = (key, value, scale) =>
  key === "criticalDamage" ? round(value * scale, 2) : Math.round(value * scale);

// Item Generation
export const generateRandomItem = (slot) => {
  const config = SLOT_CONFIG[slot];
  if (!config) return null;
  const p = getPlayer();
  const level = p?.level || 1;

  // 3 lower to 5 higher than the player's level
  const iLevel = Math.max(1, level + Math.floor(Math.random() * 9) - 3);
  const rarity = rollRarity();
  const condition = pick(CONDITIONS);
  const base = pick(config.bases);
  const twoHanded = !!base.twoHanded;
  const scale = twoHanded ? TWO_HANDED_MULT : 1;

  // Base roll 1-5 plus rarity bonus (not scaled by iLevel); two-handed weapons scale that, then condition applies
  const mainStat = {
    stat: base.stat,
    value: Math.max(
      0,
      Math.round((randInt(5) + rarity.mainStatBonus) * scale) +
        condition.mainStatModifier,
    ),
  };

  // Unique substats
  const pool = [...SUBSTAT_POOLS[config.pool]];
  const subStats = {};
  const count = Math.min(rarity.substats, pool.length);
  for (let i = 0; i < count; i++) {
    const key = pool.splice(Math.floor(Math.random() * pool.length), 1)[0];
    subStats[key] = scaleValue(key, rollSubStatValue(key, iLevel), scale);
  }

  const abilityPool = ABILITIES.filter((a) => a.slots.includes(slot));
  let ability = null;
  if (abilityPool.length && Math.random() < rarity.abilityChance) {
    const { name, description } = pick(abilityPool);
    ability = { name, description };
  }

  const subValue = Object.entries(subStats).reduce(
    (sum, [k, v]) => sum + v * SUBSTAT_PRICE[k],
    0,
  );
  const price = Math.max(
    1,
    Math.round(
      (5 +
        iLevel * 2 +
        mainStat.value * 2 +
        subValue +
        (ability ? iLevel * 5 : 0)) *
        rarity.priceMult *
        config.priceMult *
        condition.valueMultiplier,
    ),
  );

  const tier = Math.min(MATERIALS.metal.length - 1, Math.floor((iLevel - 1) / 25));
  const prefix = MATERIALS[base.material][tier];
  const name = [condition.name, ability?.name, prefix, base.name]
    .filter(Boolean)
    .join(" ");

  return {
    id: newId(),
    name,
    slot,
    twoHanded,
    rarity: rarity.name,
    condition: condition.name,
    iLevel,
    price,
    description: "",
    mainStat,
    subStats,
    ability,
  };
};

