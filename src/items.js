const formatValue = (stat, v) => {
  const n = PERCENT_STATS.includes(stat)
    ? `${round(Math.abs(v) * 100, 1)}%`
    : Math.abs(v);
  return `${v < 0 ? "-" : "+"}${n}`;
};

export const itemTooltip = (item, extra) => {
  if (!item) return null;
  const slot = SLOTS.find((s) => s.type === item.slot);
  const stats = [];
  if (item.mainStat) {
    stats.push({
      label: STAT_LABELS[item.mainStat.stat] || item.mainStat.stat,
      value: formatValue(item.mainStat.stat, item.mainStat.value),
      color: "#ffd479",
    });
  }
  for (const [k, v] of Object.entries(item.subStats || {})) {
    stats.push({
      label: STAT_LABELS[k] || k,
      value: formatValue(k, v),
      color: v < 0 ? "#ff6b6b" : "#7bd88f",
    });
  }
  const slotLabel = slot ? slot.label.replace(/ \d$/, "") : item.slot;
  const level = getPlayer()?.level || 1;
  const tags = [slotLabel, item.twoHanded && "Two-handed"].filter(Boolean);
  const abilityText = item.ability
    ? `${item.ability.name}: ${item.ability.description}`
    : "";
  return {
    title: item.name,
    titleColor: RARITY_COLORS[item.rarity],
    subtitle: `${item.rarity}, Item Level ${item.iLevel} • Equip level ${getEquipLevel(item)}`,
    description: [abilityText].filter(Boolean),
    stats,
    footer: [
      extra,
      !canEquip(item, level) && `Requires level ${getEquipLevel(item)}`,
      `Value: ${item.price}`,
    ]
      .filter(Boolean)
      .join(" • "),
    tags,
  };
};

// Equip level is iLevel + rarity rank (Common 1 ... Legendary 5), capped at 100.
// Always derived, so items saved under an older formula stay consistent.
export const getEquipLevel = (item) => {
  const rank = RARITIES.findIndex((r) => r.name === item?.rarity);
  return Math.min(100, Math.max(1, (item?.iLevel || 1) + rank));
};

export const canEquip = (item, level = getPlayer()?.level || 1) =>
  level >= getEquipLevel(item);

